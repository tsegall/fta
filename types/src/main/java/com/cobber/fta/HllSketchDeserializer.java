package com.cobber.fta;

import java.io.IOException;
import java.util.Base64;

import org.apache.datasketches.hll.HllSketch;

import com.fasterxml.jackson.core.JsonParser;
import com.fasterxml.jackson.databind.DeserializationContext;
import com.fasterxml.jackson.databind.JsonDeserializer;

public class HllSketchDeserializer extends JsonDeserializer<HllSketch> {
	@Override
	public HllSketch deserialize(final JsonParser p, final DeserializationContext ctx) throws IOException {
		return HllSketch.heapify(Base64.getDecoder().decode(p.getText()));
	}
}
